const RETRIES = 5;

async function fetchWithRetry(url, init) {
  let lastError = null;

  for (let attempt = 1; attempt <= RETRIES; attempt += 1) {
    try {
      return await fetch(url, { ...init, signal: AbortSignal.timeout(120000) });
    } catch (error) {
      lastError = error;
      console.log('  сеть: попытка ' + attempt + ' не прошла (' + (error.cause?.code ?? error.name) + '), повтор');
      await new Promise((resolve) => setTimeout(resolve, 2000 * attempt));
    }
  }

  throw lastError;
}

async function getToken() {
  const response = await fetchWithRetry(OAUTH_URL, {
    method: 'POST',
    headers: {
      'content-type': 'application/x-www-form-urlencoded',
      accept: 'application/json',
      RqUID: randomUUID(),
      Authorization: `Basic ${process.env.GIGACHAT_AUTH_KEY}`,
    },
    body: new URLSearchParams({ scope: process.env.GIGACHAT_SCOPE ?? 'GIGACHAT_API_PERS' }),
  });

  if (!response.ok) {
    throw new Error(`oauth ${response.status}: ${await response.text()}`);
  }

  return (await response.json()).access_token;
}

